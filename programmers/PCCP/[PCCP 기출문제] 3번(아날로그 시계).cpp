#include <string>
#include <vector>
using namespace std;

int solution(int h1, int m1, int s1, int h2, int m2, int s2) {
    int answer = 0;

    // 시:분:초 -> 자정 기준 경과 초로 변환
    int start = h1 * 60 * 60 + m1 * 60 + s1;
    int end = h2 * 60 * 60 + m2 * 60 + s2;

    // h[0]/m[0]/s[0]: 현재 초의 시침/분침/초침 각도
    // h[1]/m[1]/s[1]: 다음 초의 시침/분침/초침 각도
    double h[2], m[2], s[2];

    // 시작 시각의 바늘 각도 계산
    h[0] = start % 43200 * (1 / (double)120); // 시침: 12시간(43200초)에 360도
    m[0] = start % 3600 * (1 / (double)10);   // 분침: 60분(3600초)에 360도
    s[0] = start % 60 * (double)6;            // 초침: 60초에 360도

    // 시작 시각에 세 바늘이 모두 겹치는 경우(0시/12시 정각) 알람 1회
    if (h[0] == s[0] && m[0] == s[0]) {
        answer++;
    }

    // 1초 단위 구간 [i, i+1]마다 겹침 발생 여부 검사
    for (int i = start; i < end; i++) {
        // j=0: 구간 시작 각도, j=1: 구간 끝 각도
        for (int j = 0; j < 2; j++) {
            h[j] = (i + j) % 43200 * (1 / (double)120);
            m[j] = (i + j) % 3600 * (1 / (double)10);
            s[j] = (i + j) % 60 * (double)6;
        }

        // 한 바퀴 돌아 각도가 0이 된 경우 360으로 보정 (증가하던 각도의 흐름을 유지해 대소 비교가 깨지지 않도록 함)
        if (h[1] == 0) h[1] = 360;
        if (m[1] == 0) m[1] = 360;
        if (s[1] == 0) s[1] = 360;

        // 구간 끝에서 세 바늘이 모두 겹치는 경우 -> 알람 1회만 카운트
        if (h[1] == s[1] && m[1] == s[1]) {
            answer++;
        } else {
            // 시침-초침: 시작엔 시침이 앞서다 끝에서 초침이 따라잡으면 겹침 발생
            if (h[0] > s[0] && h[1] <= s[1]) {
                answer++;
            }
            // 분침-초침: 같은 방식으로 판별
            if (m[0] > s[0] && m[1] <= s[1]) {
                answer++;
            }
        }
    }

    return answer;
}